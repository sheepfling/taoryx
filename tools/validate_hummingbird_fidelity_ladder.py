TelemetryRow = dict[str, Any]


@dataclass(frozen=True, slots=True)
class MissionPhase:
    phase_id: str
    target_m: tuple[float, float, float]
    target_yaw_rad: float
    duration_s: float
    landing: bool = False
    shutdown: bool = False
    disturbance_velocity_m_s: tuple[float, float, float] | None = None
    ####


def _clamp(value: float, lower: float, upper: float) -> float:
    return max(lower, min(upper, value))
    ####


def _distance(left: list[float], right: tuple[float, float, float]) -> float:
    return math.sqrt(sum((float(a) - float(b)) ** 2 for a, b in zip(left, right, strict=True)))
    ####


def _angle_error(target: float, actual: float) -> float:
    return (target - actual + math.pi) % (2.0 * math.pi) - math.pi
    ####


def _phases() -> tuple[MissionPhase, ...]:
    return (
        MissionPhase("takeoff_altitude_gate", (0.0, 0.0, 2.0), 0.0, 5.0),
        MissionPhase("yaw_gate", (0.0, 0.0, 2.0), math.pi / 2.0, 4.0),
        MissionPhase("box_east", (2.0, 0.0, 2.0), math.pi / 2.0, 5.0),
        MissionPhase("box_north", (2.0, 2.0, 2.0), math.pi / 2.0, 5.0),
        MissionPhase("box_west", (0.0, 2.0, 2.0), math.pi / 2.0, 5.0),
        MissionPhase("box_south_return", (0.0, 0.0, 2.0), math.pi / 2.0, 5.0),
        MissionPhase(
            "disturbance_recovery",
            (0.0, 0.0, 2.0),
            math.pi / 2.0,
            6.0,
            disturbance_velocity_m_s=(0.8, -0.6, 0.0),
        ),
        MissionPhase("landing_contact", (0.0, 0.0, 0.0), math.pi / 2.0, 5.0, landing=True),
        MissionPhase("post_contact_shutdown", (0.0, 0.0, 0.0), math.pi / 2.0, 2.5, shutdown=True),
    )
    ####


def _command_for_phase(model: HummingbirdPseudo6DOFModel, state: Any, phase: MissionPhase) -> HummingbirdPseudo6DOFCommand:
    position = state.position_m
    velocity = state.velocity_m_s
    ax = _clamp(1.2 * (phase.target_m[0] - position[0]) - 1.6 * velocity[0], -3.0, 3.0)
    ay = _clamp(1.2 * (phase.target_m[1] - position[1]) - 1.6 * velocity[1], -3.0, 3.0)
    if phase.landing:
        az = _clamp(0.4 * (phase.target_m[2] - position[2]) - 0.8 * velocity[2], -0.2, 0.2)
    else:
        az = _clamp(1.8 * (phase.target_m[2] - position[2]) - 1.8 * velocity[2], -1.0, 1.0)
    required_vertical_force = model.mass_kg * (model.gravity_m_s2 + az)
    thrust = model.mass_kg * math.sqrt(ax * ax + ay * ay + (model.gravity_m_s2 + az) ** 2)
    thrust = max(thrust, required_vertical_force, 0.0)
    pitch = math.asin(_clamp(model.mass_kg * ax / max(thrust, 1.0e-9), -0.5, 0.5))
    roll = math.asin(_clamp(-model.mass_kg * ay / max(thrust, 1.0e-9), -0.5, 0.5))
    requested_ratio = _clamp(thrust / model.maximum_thrust_n / max(state.battery_fraction, 1.0e-6), 0.0, 1.0)
    return HummingbirdPseudo6DOFCommand(
        roll_rad=roll,
        pitch_rad=pitch,
        yaw_rad=phase.target_yaw_rad,
        thrust_ratio=requested_ratio,
        motors_enabled=not phase.shutdown,
    )
    ####


def _command_for_phase_3dof(model: Hummingbird3DOFModel, state: Hummingbird3DOFState, phase: MissionPhase) -> Hummingbird3DOFCommand:
    """Return a translational force command without attitude channels."""

    position = state.position_m
    velocity = state.velocity_m_s
    ax = _clamp(1.2 * (phase.target_m[0] - position[0]) - 1.6 * velocity[0], -3.0, 3.0)
    ay = _clamp(1.2 * (phase.target_m[1] - position[1]) - 1.6 * velocity[1], -3.0, 3.0)
    if phase.landing:
        az = _clamp(0.4 * (phase.target_m[2] - position[2]) - 0.8 * velocity[2], -0.2, 0.2)
    else:
        az = _clamp(1.8 * (phase.target_m[2] - position[2]) - 1.8 * velocity[2], -1.0, 1.0)
    thrust_vector = (
        model.mass_kg * ax,
        model.mass_kg * ay,
        model.mass_kg * (model.gravity_m_s2 + az),
    )
    return Hummingbird3DOFCommand(
        thrust_vector_n=thrust_vector,
        motors_enabled=not phase.shutdown,
    )
    ####


def run_mission(
    *,
    dt_s: float = 0.05,
    model: HummingbirdPseudo6DOFModel | None = None,
    initial_state: HummingbirdPseudo6DOFState | None = None,
) -> tuple[list[TelemetryRow], tuple[MissionPhase, ...]]:
    """Run the deterministic pseudo mission and return truth telemetry."""

    selected_model = HummingbirdPseudo6DOFModel() if model is None else model
    state = selected_model.initial_state() if initial_state is None else initial_state
    rows: list[TelemetryRow] = []
    for phase in _phases():
        sample_count = round(phase.duration_s / dt_s)
        disturbance_applied = False
        for sample_index in range(sample_count):
            if sample_index == 0 and phase.disturbance_velocity_m_s is not None:
                updated_velocity = tuple(
                    float(a) + float(b)
                    for a, b in zip(state.velocity_m_s, phase.disturbance_velocity_m_s, strict=True)
                )
                state = replace(
                    state,
                    velocity_m_s=(updated_velocity[0], updated_velocity[1], updated_velocity[2]),
                )
                disturbance_applied = True
            command = _command_for_phase(selected_model, state, phase)
            state, row = selected_model.step(state, command, dt_s)
            row = dict(row)
            row["phase_id"] = phase.phase_id
            row["target_position_m"] = list(phase.target_m)
            row["target_yaw_rad"] = phase.target_yaw_rad
            row["disturbance_applied"] = disturbance_applied and sample_index == 0
            row["disturbance_velocity_impulse_m_s"] = list(phase.disturbance_velocity_m_s or (0.0, 0.0, 0.0))
            rows.append(row)
    return rows, _phases()
    ####


