#!/usr/bin/env python3
"""Build the Alpha 3 Hummingbird fidelity-ladder development packet.

The mission is intentionally small but characteristic: takeoff, altitude
capture, yaw, a four-corner box, return, contact, and post-contact shutdown.
The controller supplies commands; the objective evaluator scans truth
telemetry independently and never accepts a controller transition as proof.
The point-mass record is generated by an independent translational force
model; it does not inherit attitude, yaw, or motor behavior from the pseudo
runner.
"""

